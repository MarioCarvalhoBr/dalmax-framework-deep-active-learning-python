"""Tests for the KMH parameter-sweep params files (`files_config/ablations/kmh_sweep/`).

The files are generated by `scripts/campaign/build_kmh_sweep_configs.py`; these tests check that the
committed files match the generator, that every one loads through the real config loader, and the
sweep's structural rules (budget-matched shapes, the preserved reference sample sizes, knob values).
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import pytest

from dalmax.config.loader import load_experiment_config

REPO_ROOT = Path(__file__).resolve().parent.parent
SWEEP_DIR = REPO_ROOT / "files_config/ablations/kmh_sweep"


def _generator():
    spec = importlib.util.spec_from_file_location(
        "build_kmh_sweep_configs", REPO_ROOT / "scripts/campaign/build_kmh_sweep_configs.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules["build_kmh_sweep_configs"] = module
    spec.loader.exec_module(module)
    return module


GEN = _generator()
EXPECTED = GEN.expected_files()


def _load(rel: str, nq: int):
    return load_experiment_config(
        REPO_ROOT / rel, "DANINHAS", strategy_name="RepresentationStrategy", seed=1,
        n_init_labeled=10, n_query=nq, n_round=1, dir_results="results/_test_unused/", device="cpu")


def test_committed_configs_match_the_generator() -> None:
    for rel, text in EXPECTED.items():
        assert (REPO_ROOT / rel).read_text() == text, f"{rel} drifted: rerun the generator"
    on_disk = {p.relative_to(REPO_ROOT).as_posix() for p in SWEEP_DIR.rglob("*.json")}
    assert on_disk == set(EXPECTED), "stray or missing files under kmh_sweep/"


def test_file_counts_per_budget() -> None:
    per_nq = {nq: sum(f"/nq{nq}/" in rel and "/micro/" not in rel for rel in EXPECTED) for nq in GEN.BUDGETS}
    assert per_nq == {10: 17, 50: 17, 100: 21}
    assert sum(per_nq.values()) == 55


@pytest.mark.parametrize("rel", sorted(EXPECTED))
def test_every_config_loads(rel: str) -> None:
    nq = int(rel.split("/nq")[1].split("/")[0])
    cfg = _load(rel, nq)
    assert cfg.strategy_name == "RepresentationStrategy"
    assert cfg.dataset.embedding.extractor == "resnet_imagenet"
    h = cfg.dataset.selection.hierarchy
    assert h is not None and h.n_levels == len(h.n_clusters) == len(h.sample_sizes)
    assert all(s <= k for s, k in zip(h.sample_sizes, h.n_clusters, strict=True))
    assert ("micro" in rel) == ("daninhas_micro" in cfg.dataset.data_dir)


def _clusters(rel: str) -> tuple[int, ...]:
    return tuple(json.loads((REPO_ROOT / rel).read_text())["DANINHAS"]["selection"]["hierarchy"]["n_clusters"])


@pytest.mark.parametrize("nq", [10, 50])
def test_budget_matched_rule(nq: int) -> None:
    base = f"files_config/ablations/kmh_sweep/nq{nq}"
    assert _clusters(f"{base}/hier_L1_k{nq}.json") == (nq,)
    assert _clusters(f"{base}/hier_L2_matched.json") == (6 * nq, nq)
    assert _clusters(f"{base}/hier_L3_matched.json") == (6 * nq, 2 * nq, nq)


def test_nq100_has_no_duplicate_of_existing_shapes() -> None:
    names = {p.stem for p in (SWEEP_DIR / "nq100").glob("*.json")}
    assert "hier_L3_matched" not in names and not any(n.startswith("hier_L3_matched__") for n in names)
    assert "hier_L1_k{nq}" not in names and "hier_L1_k100" in names
    assert _clusters("files_config/ablations/kmh_sweep/nq100/hier_L2_matched.json") == (600, 100)


@pytest.mark.parametrize("nq", GEN.BUDGETS)
def test_reference_keeps_historical_sample_sizes(nq: int) -> None:
    h = _load(f"files_config/ablations/kmh_sweep/nq{nq}/hier_L3_ref.json", nq).dataset.selection.hierarchy
    assert (h.n_clusters, h.sample_sizes) == ((600, 200, 100), (30, 15, 2))


def test_sample_size_rule_reproduces_existing_hierarchy_files() -> None:
    for name, clusters, samples in (
        ("hier_L4_k800_600_200_100", (800, 600, 200, 100), (40, 30, 10, 5)),
        ("hier_L1_k100", (100,), (5,)), ("hier_L1_k200", (200,), (10,)),
        ("hier_L1_k600", (600,), (30,)), ("hier_L2_k200_100", (200, 100), (10, 5)),
    ):
        assert GEN.sample_sizes_for(clusters) == samples
        h = _load(f"files_config/ablations/rnhal/{name}.json", 100).dataset.selection.hierarchy
        assert (h.n_clusters, h.sample_sizes) == (clusters, samples)


def test_micro_reference_matches_params_kmh_micro() -> None:
    h = _load("files_config/ablations/kmh_sweep/micro/nq100/hier_L3_ref.json", 5).dataset.selection.hierarchy
    ref = _load("files_config/campaign/params_kmh_micro.json", 5).dataset.selection.hierarchy
    assert (h.n_clusters, h.sample_sizes) == (ref.n_clusters, ref.sample_sizes) == ((60, 20, 10), (3, 2, 2))


def test_knob_configs_differ_from_their_base_only_in_the_knob() -> None:
    for nq in GEN.BUDGETS:
        for base_name in ("hier_L3_ref", "hier_L3_matched"):
            if not (SWEEP_DIR / f"nq{nq}/{base_name}.json").exists():
                continue
            base = _load(f"files_config/ablations/kmh_sweep/nq{nq}/{base_name}.json", nq).dataset.selection.hierarchy
            for suffix, key, value in GEN.KNOBS:
                h = _load(f"files_config/ablations/kmh_sweep/nq{nq}/{base_name}__{suffix}.json", nq)
                h = h.dataset.selection.hierarchy
                assert getattr(h, key) == value and getattr(base, key) != value
                assert (h.n_clusters, h.sample_sizes) == (base.n_clusters, base.sample_sizes)


STAGE2_EXPECTED: dict[str, tuple[tuple[int, ...], tuple[int, ...]]] = {
    "hier_L5_k1000_800_600_200_100": ((1000, 800, 600, 200, 100), (50, 40, 30, 10, 5)),
    "hier_L4_k1200_600_200_100": ((1200, 600, 200, 100), (60, 30, 10, 5)),
    "hier_L4_k800_600_200_50": ((800, 600, 200, 50), (40, 30, 10, 3)),
    "hier_L3_k800_600_100": ((800, 600, 100), (40, 30, 5)),
    "hier_L1_k50": ((50,), (3,)),
    "hier_L1_k20": ((20,), (2,)),
    "hier_L4_k800_600_200_100__no_resampling": ((800, 600, 200, 100), (40, 30, 10, 5)),
    "hier_L4_k800_600_200_100__resample_random": ((800, 600, 200, 100), (40, 30, 10, 5)),
    "hier_L4_k800_600_200_100__sample_x2": ((800, 600, 200, 100), (80, 60, 20, 10)),
    "hier_L2_matched__no_resampling": ((600, 100), (30, 5)),
}


@pytest.mark.parametrize("name", sorted(STAGE2_EXPECTED))
def test_stage2_configs_load_with_expected_shapes(name: str) -> None:
    rel = f"files_config/ablations/kmh_sweep/nq100/{name}.json"
    h = _load(rel, 100).dataset.selection.hierarchy
    assert (h.n_clusters, h.sample_sizes) == STAGE2_EXPECTED[name]
    assert json.loads((REPO_ROOT / rel).read_text())["_comment"].startswith("KMH sweep stage 2 (nq100 only, 2026-11-08)")
    assert (SWEEP_DIR / f"micro/nq100/{name}.json").exists()


def test_stage2_knobs_and_scope() -> None:
    def hier(name: str):
        return _load(f"files_config/ablations/kmh_sweep/nq100/{name}.json", 100).dataset.selection.hierarchy

    assert hier("hier_L4_k800_600_200_100__no_resampling").n_resamples == 0
    assert hier("hier_L4_k800_600_200_100__resample_random").resample_strategy == "random"
    assert hier("hier_L2_matched__no_resampling").n_resamples == 0
    assert hier("hier_L4_k800_600_200_100__sample_x2").n_resamples == hier("hier_L4_k800_600_200_100").n_resamples
    stage2_files = {f"{n}.json" for n, _, _ in GEN.stage2_points()}
    assert {n for n, _, _ in GEN.stage2_points()} == set(STAGE2_EXPECTED)
    for nq in (10, 50):  # a stage-1 file may share a name (hier_L1_k50 at nq50) but is a different config
        assert not {f"{n}.json" for n, h, k in GEN.grid(nq) if GEN.is_stage2(h, k, nq)} & stage2_files
    assert GEN.STAGE2_NQ == 100 and all(GEN.is_stage2(h, k, 100) for n, h, k in GEN.stage2_points())


def test_stage2_micro_sample_x2_is_capped_doubled_rule() -> None:
    h = _load("files_config/ablations/kmh_sweep/micro/nq100/hier_L4_k800_600_200_100__sample_x2.json", 5)
    h = h.dataset.selection.hierarchy
    assert (h.n_clusters, h.sample_sizes) == ((80, 60, 20, 10), (8, 6, 4, 4))
